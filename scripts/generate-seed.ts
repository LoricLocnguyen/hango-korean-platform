// Generates supabase/seed.sql from the app's bundled content data
// (lib/seed-data.ts). Run: node scripts/generate-seed.ts
// The output is idempotent: every INSERT uses ON CONFLICT DO NOTHING,
// and UUID primary keys are derived deterministically from local ids.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import {
  fullLevelsData,
  fullVocabulariesData,
  fullGrammarData,
  sampleQuizQuestions,
  sampleListeningExercises,
  sampleSpeakingScenarios,
} from '../lib/seed-data.ts';

function uuidFor(kind: string, localId: string): string {
  const h = createHash('md5').update(`hango:${kind}:${localId}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function q(v: string | null | undefined): string {
  if (v === null || v === undefined) return 'NULL';
  return `'${v.replace(/'/g, "''")}'`;
}

function n(v: number | null | undefined, fallback = 0): string {
  return String(v === null || v === undefined ? fallback : v);
}

function arr(v: string[] | undefined): string {
  if (!v || v.length === 0) return 'NULL';
  return `ARRAY[${v.map((s) => q(s)).join(', ')}]::text[]`;
}

function jsonb(v: unknown): string {
  return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
}

const POS_EN: Record<string, string> = {
  'Danh từ': 'noun',
  'Động từ': 'verb',
  'Tính từ': 'adjective',
  'Phó từ': 'adverb',
  'Cụm từ': 'phrase',
};

